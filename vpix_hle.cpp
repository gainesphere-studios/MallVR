                        static unsigned long nu = 0; if (nu++ % 3000 == 0) lg("ARM_TO_GUN f=%lu play: upper arm IK, shoulder->grip %.0f, bones %.0f + %.0f (x%.2f)", frame, d, L1, L2, kst);
