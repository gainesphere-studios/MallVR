static void lg(const char *fmt, ...) {
    if (!flog || log_lines >= CALL_LOG_MAX) return;
    va_list ap; va_start(ap, fmt); vfprintf(flog, fmt, ap); va_end(ap);
    fputc('\n', flog);
    if (log_lines < 5000 || (log_lines & 31) == 0) fflush(flog);   /* startup lines survive a kill */
    if (++log_lines == CALL_LOG_MAX) fprintf(flog, "... call log capped\n");
}

static bool parse_hex(const char *s, uint8_t *out, size_t n) {
    for (size_t i = 0; i < n; i++) { unsigned v; if (sscanf(s + 2 * i, "%2x", &v) != 1) return false; out[i] = (uint8_t)v; }
    return true;
}

/* PIXMODEL record in the card tables: 0xAC bytes (PIX 1.05.61+: DAC, DN2, BOX, ZONE, GHOST ...), 0x8C in PEARL's older library 1.05.50 (palette 8 entries,
   every field after it 0x20 earlier: bitmap pointer +0x80, flags +0x88). Set by the hook table line 'modelstride 8C' (re/gen_hooks.py reads
   PIX_SetModel's flags test); PEARL also by the table name; VPIX_MODEL_STRIDE overrides. */
static uint32_t model_stride = 0xAC, model_shift = 0;
static bool load_hooks(const char *path) {
    FILE *f = fopen(path, "r");
    if (!f) { lg("HLE: cannot open hook table %s", path); return false; }
    char line[512];
    while (fgets(line, sizeof(line), f)) {
        char kw[32], a[128], b[128], c[128], d[128]; unsigned e = 0; int rv = 0;
        int n = sscanf(line, "%31s %127s %127s %127s %127s %u %d", kw, a, b, c, d, &e, &rv);
        if (n < 1 || kw[0] == '#') continue;
        if (!strcmp(kw, "anchor") && n >= 4) {
            anchor_name = a; anchor_st = (uint32_t)strtoul(b, NULL, 16); parse_hex(c, anchor_pro, 16);
        } else if (!strcmp(kw, "dataref") && n >= 3 && ndataref < 2) {
            dataref_code[ndataref] = (uint32_t)strtoul(a, NULL, 16); dataref_target[ndataref] = (uint32_t)strtoul(b, NULL, 16); ndataref++;
        } else if (!strcmp(kw, "global") && n >= 3) {
            globals[a] = (uint32_t)strtoul(b, NULL, 16);
        } else if (!strcmp(kw, "code") && n >= 3) {     /* named code location (static address) */
            codes[a] = (uint32_t)strtoul(b, NULL, 16);
        } else if (!strcmp(kw, "watch") && n >= 3) {
            watches.push_back({a, (uint32_t)strtoul(b, NULL, 16)});
        } else if (!strcmp(kw, "region") && n >= 4) {
            regions.push_back({a, (uint32_t)strtoul(b, NULL, 16), (uint32_t)strtoul(c, NULL, 16)});
        } else if (!strcmp(kw, "modelstride") && n >= 2) {   /* gen_hooks.py: older PIX lib record size (0x8C) */
            model_stride = (uint32_t)strtoul(a, NULL, 16); model_shift = 0xAC - model_stride;
        } else if (!strcmp(kw, "hook") && n >= 6) {
            /* VPIX_NET: the emulated card is there, so the game's own NET library runs (no stubs) */
            if (VPIX_NET_Enabled() && (!strncmp(a, "NET_", 4) || !strncmp(a, "NETI_", 5))) { lg("HLE: %s left native (network on)", a); continue; }
            VHook h; h.name = a; h.mode = b[0]; h.st = (uint32_t)strtoul(c, NULL, 16);
            parse_hex(d, h.pro, 16); h.retpop = e; h.calls = 0; h.retval = (uint32_t)rv;
            h.imm = (uint32_t)h.pro[1] | ((uint32_t)h.pro[2] << 8) | ((uint32_t)h.pro[3] << 16) | ((uint32_t)h.pro[4] << 24);
            hooks.push_back(h);
        }
    }
    fclose(f);
    lg("HLE: hook table %s: %u hooks, %u regions", path, (unsigned)hooks.size(), (unsigned)regions.size());
    return anchor_st != 0 && !hooks.empty();
}

/* guest memory helpers (linear addresses; DOS/4GW flat selectors have base 0) */
static std::string rd_str(uint32_t a, size_t max = 128) {
    std::string s;
    for (size_t i = 0; i < max; i++) { char ch = (char)mem_readb(a + i); if (!ch) break; s += ch; }
    return s;
}
static std::string rd_hex(uint32_t a, size_t n) {
    std::string s; char b[4];
    for (size_t i = 0; i < n; i++) { snprintf(b, sizeof(b), "%02x", mem_readb(a + i)); s += b; if ((i & 3) == 3 && i + 1 < n) s += ' '; }
    return s;
}

static bool read_dos_file(const std::string &name, std::vector<uint8_t> &out) {
    uint16_t fh;
    if (!DOS_OpenFile(name.c_str(), 0, &fh)) return false;
    for (;;) {
        static uint8_t buf[0x8000]; uint16_t n = sizeof(buf);
        if (!DOS_ReadFile(fh, buf, &n) || n == 0) break;
        out.insert(out.end(), buf, buf + n);
        if (n < sizeof(buf)) break;
    }
    DOS_CloseFile(fh);
    return true;
}

