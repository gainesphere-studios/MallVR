/*
 *  Virtuality SU2000 — function-level HLE of the PIX graphics library.
 *
 *  The games are Watcom DOS/4GW programs linked against Division's PIX library. Instead
 *  of emulating the PIX1000 cards (two MC88110s running MAINA/MAINB.OUT), we patch the
 *  library's entry points inside the running game with DOSBox callbacks:
 *
 *    R hooks  replace a function that talks to the card (load model, render, sync...).
 *    L hooks  log the call, then let the library's own pure bookkeeping run natively.
 *
 *  The library keeps the whole scene in its own tables (model[], view[], window[], light[]...),
 *  so at every PIX_RenderSwap we snapshot those tables and hand them to our renderer.
 *
 *  Hook table: env VPIX_HOOKS (generated by re/gen_hooks.py from the game's debug symbols).
 *  Output:     VPIX_LOG + ".calls" (text call log), VPIX_LOG + ".scene" (binary snapshots).
 *
 *  Calling convention is Watcom register: args in EAX, EDX, EBX, ECX, then stack (callee
 *  pops); result in EAX; every other register preserved.
 */

